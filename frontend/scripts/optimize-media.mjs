import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const ffmpegPath = require('ffmpeg-static');
const sharp = require('sharp');

const ROOT = process.cwd();
const BRAND_DIR = path.join(ROOT, 'public', 'brand');
const IMAGES_DIR = path.join(ROOT, 'public', 'images');
const PLACEHOLDER_OUT = path.join(ROOT, 'src', 'lib', 'media-placeholders.ts');

function findAtomOffset(buffer, atomName) {
  return buffer.indexOf(Buffer.from(atomName, 'ascii'));
}

function optimizeHeroVideo() {
  const mp4Path = path.join(BRAND_DIR, 'evorah-hero.mp4');
  const mp4Tmp = path.join(BRAND_DIR, 'evorah-hero.faststart.mp4');
  const webmPath = path.join(BRAND_DIR, 'evorah-hero.webm');
  const posterPath = path.join(BRAND_DIR, 'evorah-hero-poster.webp');
  const posterTmpPng = path.join(BRAND_DIR, '.poster-tmp.png');

  if (!fs.existsSync(mp4Path)) {
    throw new Error(`Hero video not found: ${mp4Path}`);
  }

  const mp4BeforeBytes = fs.statSync(mp4Path).size;
  const beforeBuf = fs.readFileSync(mp4Path);
  const moovBefore = findAtomOffset(beforeBuf, 'moov');
  const mdatBefore = findAtomOffset(beforeBuf, 'mdat');

  // 1. Remux MP4 with moov atom at the front (+faststart) for instant progressive playback
  execFileSync(
    ffmpegPath,
    ['-y', '-i', mp4Path, '-c', 'copy', '-movflags', '+faststart', mp4Tmp],
    { stdio: 'ignore' }
  );
  fs.renameSync(mp4Tmp, mp4Path);

  const mp4AfterBytes = fs.statSync(mp4Path).size;
  const afterBuf = fs.readFileSync(mp4Path);
  const moovAfter = findAtomOffset(afterBuf, 'moov');
  const mdatAfter = findAtomOffset(afterBuf, 'mdat');

  // 2. Encode lightweight VP9 WebM with frequent keyframes (-g 30) for faster Chromium/Firefox decode & looping
  execFileSync(
    ffmpegPath,
    [
      '-y',
      '-i',
      mp4Path,
      '-c:v',
      'libvpx-vp9',
      '-crf',
      '30',
      '-b:v',
      '0',
      '-row-mt',
      '1',
      '-deadline',
      'good',
      '-cpu-used',
      '2',
      '-g',
      '30',
      '-an',
      webmPath,
    ],
    { stdio: 'ignore' }
  );
  const webmBytes = fs.statSync(webmPath).size;

  // 3. Extract peak brand-mark frame and convert to tiny WebP poster via sharp
  execFileSync(
    ffmpegPath,
    ['-y', '-ss', '5.5', '-i', mp4Path, '-frames:v', '1', posterTmpPng],
    { stdio: 'ignore' }
  );

  return sharp(posterTmpPng)
    .resize({ width: 960, withoutEnlargement: true })
    .webp({ quality: 80, effort: 6 })
    .toFile(posterPath)
    .then(() => {
      if (fs.existsSync(posterTmpPng)) fs.unlinkSync(posterTmpPng);
      const posterBytes = fs.statSync(posterPath).size;
      return {
        mp4BeforeBytes,
        mp4AfterBytes,
        moovBefore,
        mdatBefore,
        moovAfter,
        mdatAfter,
        webmBytes,
        posterBytes,
      };
    });
}

async function optimizeHeroAndEditorialImages() {
  const heroPng = path.join(IMAGES_DIR, 'hero-model-clean.png');
  const heroWebp = path.join(IMAGES_DIR, 'hero-model-clean.webp');
  const heroSource = fs.existsSync(heroPng) ? heroPng : heroWebp;
  const heroTmp = path.join(IMAGES_DIR, '.hero-model-clean.tmp.webp');

  const heroBeforeBytes = fs.statSync(heroWebp).size;

  // Resize to 828px wide (exact Retina 2x match for Next image deviceSizes & 380px hero slot)
  // while preserving crisp alpha channel edges
  await sharp(heroSource)
    .resize({ width: 828, withoutEnlargement: true })
    .webp({ quality: 88, alphaQuality: 96, effort: 6 })
    .toFile(heroTmp);

  fs.renameSync(heroTmp, heroWebp);
  const heroMeta = await sharp(heroWebp).metadata();
  const heroAfterBytes = fs.statSync(heroWebp).size;

  // Generate tiny inline blurDataURL strings for instant first paint
  const heroBlurBuf = await sharp(heroWebp)
    .resize({ width: 16 })
    .webp({ quality: 30, alphaQuality: 60 })
    .toBuffer();
  const heroBlurDataURL = `data:image/webp;base64,${heroBlurBuf.toString('base64')}`;

  const editorialWebp = path.join(IMAGES_DIR, 'editorial-hand.webp');
  const editorialBlurBuf = await sharp(editorialWebp)
    .resize({ width: 16 })
    .webp({ quality: 30 })
    .toBuffer();
  const editorialBlurDataURL = `data:image/webp;base64,${editorialBlurBuf.toString('base64')}`;

  const tsContent = `// Auto-generated by scripts/optimize-media.mjs via sharp
export const HERO_MODEL_BLUR_DATA_URL =
  '${heroBlurDataURL}';

export const EDITORIAL_HAND_BLUR_DATA_URL =
  '${editorialBlurDataURL}';
`;

  fs.mkdirSync(path.dirname(PLACEHOLDER_OUT), { recursive: true });
  fs.writeFileSync(PLACEHOLDER_OUT, tsContent, 'utf8');

  return {
    heroBeforeBytes,
    heroAfterBytes,
    heroDimensions: `${heroMeta.width}x${heroMeta.height}`,
    heroBlurBytes: heroBlurDataURL.length,
    editorialBlurBytes: editorialBlurDataURL.length,
  };
}

async function main() {
  const videoStats = await optimizeHeroVideo();
  const imageStats = await optimizeHeroAndEditorialImages();
  console.log('VIDEO_OPT:', JSON.stringify(videoStats));
  console.log('IMAGE_OPT:', JSON.stringify(imageStats));
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
